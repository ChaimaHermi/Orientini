import os
from pathlib import Path
from dotenv import load_dotenv
import google.generativeai as genai

from .config import (
    GEMINI_MODEL,
    LLM_TEMPERATURE,
    LLM_MAX_OUTPUT_TOKENS
)

# ======================================================
# Charger le fichier .env depuis la racine du projet
# ======================================================
BASE_DIR = Path(__file__).resolve().parents[5]  # Orientini/
ENV_PATH = BASE_DIR / ".env"

load_dotenv(dotenv_path=ENV_PATH)

# ======================================================
# Configuration Gemini
# ======================================================
API_KEY = os.getenv("GOOGLE_API_KEY")

if not API_KEY:
    raise RuntimeError(
        f"GOOGLE_API_KEY non trouvée. Vérifiez le fichier {ENV_PATH}"
    )

genai.configure(api_key=API_KEY)


def llm_answer(question: str, context: str) -> str:
    """
    Génère une réponse en arabe naturel, de type assistant d’orientation,
    sans format technique (JSON, listes, champs).
    """
    prompt = f"""
    أنت مستشار توجيه جامعي في تونس.
    تقدّم إجابات واضحة، منظمة، وسهلة القراءة، موجّهة لتلاميذ الباكالوريا.

    السؤال:
    {question}

    المهمة الأساسية:
    - فهم السؤال بدقة مع تحديد شعبة الباكالوريا إن وُجدت.
    - استخراج الاختصاصات والتكوينات الموجودة في السياق فقط.
    - ترتيب هذه الاختصاصات حسب درجة ملاءمتها الأكاديمية لشعبة السؤال.

    قاعدة توجيه مهمة (إلزامية):
    - إذا كان السؤال مرتبطًا بشعبة باكالوريا معيّنة (مثل اقتصاد وتصرف، آداب، علوم…):
    - أعطِ الأولوية القصوى للاختصاصات الأكثر ارتباطًا منطقيًا وأكاديميًا بهذه الشعبة.
    - لا تدرج الاختصاصات البعيدة عن مسار الشعبة إلا إذا كان السؤال عامًا جدًا.
    - لا تخلط بين "يقبل الشعبة" و"مناسب للتوجيه".

    طريقة عرض الجواب (إلزامي):
    - استعمل عناوين واضحة.
    - استعمل نقاط أو شرطات "-" لتنظيم المعلومات.
    - قسّم الجواب إلى أقسام قصيرة.
    - لا تكتب فقرات طويلة متصلة.

    قواعد صارمة:
    - لا تذكر أي اختصاص أو تكوين غير موجود صراحة في السياق.
    - لا تضف أي معلومة من عندك.
    - لا تقارن بين المؤسسات.
    - لا تستنتج قبول أو رفض.
    - لا تحسب معدلات.
    - لا تذكر أسماء الحقول التقنية.
    - لا تستعمل JSON أو تنسيق برمجي.
    - أجب باللغة العربية فقط.

    البنية المطلوبة للإجابة:

    ابدأ دائمًا بعنوان:
    "📚 الاختصاصات الأكثر ملاءمة لهذا المسار"

    ثم:
    - قائمة بالاختصاصات التي تتماشى أكاديميًا مع شعبة السؤال.

    إذا وُجدت اختصاصات أخرى تقبل الشعبة ولكنها أقل ملاءمة:
    أضف عنوانًا ثانيًا:
    "📘 اختصاصات أخرى تقبل هذه الشعبة"

    ثم:
    - قائمة مختصرة دون تفصيل زائد.

    بعدها عنوان:
    "🏫 المؤسسات والجامعات التي توفر هذه الاختصاصات"

    ثم:
    - لكل جامعة أو مؤسسة:
    - اسم الجامعة
    - اسم المؤسسة إن وُجد
    - الاختصاصات المذكورة فقط

    بعدها (إن وُجدت معطيات):
    "📐 صيغ الاحتساب وملاحظات القبول"

    ثم:
    - ذكر صيغ الاحتساب كما هي في السياق
    - أو شروط عمرية أو اختبارات إن وُجدت
    - دون مقارنة أو استنتاج

    في حالة عدم وجود أي معطيات مطابقة أو ملائمة:
    اكتب فقط:
    "لا تتوفر معطيات كافية للإجابة عن هذا السؤال."

    السياق المتوفر:
    {context}

    الإجابة النهائية:
    """

    model = genai.GenerativeModel(GEMINI_MODEL)

    response = model.generate_content(
        prompt,
        generation_config={
            "temperature": LLM_TEMPERATURE,
            "max_output_tokens": LLM_MAX_OUTPUT_TOKENS
        }
    )

    if hasattr(response, "text") and response.text:
        return response.text.strip()

    return "لا تتوفر معطيات كافية للإجابة عن هذا السؤال."
